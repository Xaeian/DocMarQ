# docmarq/structure.py

"""Document structure - metadata, bookmarks, hyperlinks."""
from dataclasses import dataclass
from datetime import datetime, timezone

#----------------------------------------------------------------------------------------- Metadata

@dataclass
class Metadata:
  """Core docx properties (`core.xml`)."""
  title: str|None = None
  author: str|None = None
  subject: str|None = None
  keywords: str|None = None
  comments: str|None = None
  category: str|None = None

  def apply(self, document):
    """Write to `python-docx` `core_properties`."""
    cp = document.core_properties
    if self.title: cp.title = self.title
    if self.author: cp.author = self.author
    if self.subject: cp.subject = self.subject
    if self.keywords: cp.keywords = self.keywords
    if self.comments: cp.comments = self.comments
    if self.category: cp.category = self.category

def new_properties(document, blank:bool):
  """
  Core properties of a new document, dated now.
  A `blank` one, from python-docx's own template, loses that template's words too:
  `python-docx` the author, `generated by python-docx` the comment.
  A template of the user's keeps its own.
  """
  cp = document.core_properties
  if blank:
    names = ("title", "subject", "author", "keywords", "comments", "category", "last_modified_by")
    for name in names: setattr(cp, name, "")
  cp.revision = 1
  cp.created = cp.modified = datetime.now(timezone.utc)

#----------------------------------------------------------------------------------------- Bookmark

@dataclass
class Bookmark:
  """
  Internal bookmark anchor.
  In OOXML this is a `<w:bookmarkStart/>` + `<w:bookmarkEnd/>` pair around a range of content,
  referenced by id.
  """
  name: str
  id: int
